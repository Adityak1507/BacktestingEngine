"""Evaluate ML direction classifiers on real daily stock data and write a report.

Protocol (fixed before looking at the holdout):
  * Data: ORCL, YHOO, NVDA, GOOG daily bars (1995-2015), adjusted for dividends.
  * Label: does the stock rise from the next open to the open after that
    (the move the engine can actually trade)?
  * Walk-forward: retrain every 63 bars on labels already known, with a
    purge gap; predict the next block. Every prediction is out of sample.
  * Development period: predictions before 2010 (model/rule selection).
  * Holdout: predictions from 2010 on, scored once with the chosen settings.

Usage:
    python examples/ml_direction.py              # all models (~10 min)
    python examples/ml_direction.py --fast       # skip the random forest
"""

import argparse
import sys
import time
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backtester import Backtest, BuyAndHold, load_sample  # noqa: E402
from backtester.ml import MLSignalStrategy, classification_metrics, walk_forward  # noqa: E402

SYMBOLS = ["ORCL", "YHOO", "NVDA", "GOOG"]
SPLIT = "2010-01-01"
COSTS = {"none": (0.0, 0.0), "low (1+2 bp)": (0.0001, 0.0002), "retail (10+5 bp)": (0.001, 0.0005)}


def p_value_precision(pred: pd.Series, y: pd.Series, base_rate: float) -> float:
    """One-sided binomial test: are 'up' calls right more often than the base rate?"""
    from scipy.stats import binomtest

    n = int(pred.sum())
    k = int(((pred == 1) & (y == 1)).sum())
    return binomtest(k, n, base_rate, alternative="greater").pvalue if n else float("nan")


def score(pred: pd.DataFrame, rule: str) -> dict:
    m = classification_metrics(pred["y"], pred[f"pred_{rule}"], pred["proba"], pred["fwd"])
    m["p_value"] = p_value_precision(pred[f"pred_{rule}"], pred["y"], m["base_rate"])
    return m


def fmt_row(name: str, m: dict) -> str:
    def pc(v):
        return f"{v * 100:.1f}%"

    return (
        f"| {name} | {m['n']:,} | {pc(m['base_rate'])} | {pc(m['accuracy'])} | {pc(m['precision'])} | "
        f"{pc(m['recall'])} | {m['f1']:.3f} | {m['roc_auc']:.3f} | {m['avg_fwd_predicted_up'] * 1e4:.1f} bp | "
        f"{m['p_value']:.3f} |"
    )


HEADER = (
    "| Model | Days | Base rate | Accuracy | Precision | Recall | F1 | ROC AUC | Avg next-day return of 'up' calls | p (precision > base) |\n"
    "|---|---|---|---|---|---|---|---|---|---|"
)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fast", action="store_true", help="skip the slow random forest")
    ap.add_argument("--out", default=str(ROOT / "docs" / "ml_results.md"))
    args = ap.parse_args()

    configs = [
        ("Always up (baseline)", "always_up", "default"),
        ("Momentum (baseline)", "momentum", "default"),
        ("Logistic regression", "logreg", "default"),
        ("Logistic regression, high-confidence", "logreg", "confident"),
        ("Gradient boosting", "gradient_boosting", "default"),
    ]
    if not args.fast:
        configs += [
            ("Random forest", "random_forest", "default"),
            ("Random forest, high-confidence", "random_forest", "confident"),
        ]

    data = {s: load_sample(s) for s in SYMBOLS}
    preds, importance = {}, None
    for model in dict.fromkeys(m for _, m, _ in configs):
        t = time.perf_counter()
        parts = []
        for sym in SYMBOLS:
            r = walk_forward(data[sym], model=model)
            parts.append(r.predictions.assign(symbol=sym))
            if model == "random_forest":
                importance = r.feature_importance if importance is None else importance + r.feature_importance
        preds[model] = pd.concat(parts)
        print(f"{model:<18} {time.perf_counter() - t:6.1f}s", flush=True)

    lines = ["# ML direction classifier: results", ""]
    lines += [
        "Generated by `python examples/ml_direction.py`. Every number below is out of sample.",
        "",
        "## Setup",
        "",
        "- **Data**: daily bars for " + ", ".join(
            f"{s} ({data[s].index[0].year}–{data[s].index[-1].year})" for s in SYMBOLS
        ) + f", {sum(len(d) for d in data.values()):,} bars in total, adjusted for dividends.",
        "- **Label**: 1 if the stock rises from the next open to the following open (the return a "
        "signal at today's close can actually capture).",
        "- **Features**: 19 technical indicators known at today's close (returns, volatility, RSI, "
        "distance from moving averages, Bollinger z-score, range, gap, volume z-score).",
        "- **Walk-forward**: retrain every 63 bars on known labels only (purge gap of 2 bars); "
        "3 years minimum history.",
        "- **Selection**: models and decision rules were compared on predictions **before 2010** only. "
        "Predictions **from 2010** are a holdout scored once.",
        "",
    ]
    for title, sel in [("Holdout (2010 onward)", lambda p: p[p.index >= SPLIT]),
                       ("Development (before 2010)", lambda p: p[p.index < SPLIT])]:
        lines += [f"## {title}", "", HEADER]
        for name, model, rule in configs:
            lines.append(fmt_row(name, score(sel(preds[model]), rule)))
        lines.append("")

    best = "random_forest" if "random_forest" in preds else "logreg"
    lines += [f"## Holdout by stock ({'random forest' if best == 'random_forest' else 'logistic regression'})", "", HEADER]
    hold = preds[best][preds[best].index >= SPLIT]
    for sym in SYMBOLS:
        lines.append(fmt_row(sym, score(hold[hold["symbol"] == sym], "default")))
    lines.append("")

    if importance is not None:
        imp = (importance / importance.sum()).sort_values(ascending=False).head(8)
        lines += ["## Most important features (random forest)", "", "| Feature | Share |", "|---|---|"]
        lines += [f"| `{k}` | {v * 100:.1f}% |" for k, v in imp.items()]
        lines.append("")

    lines += [
        "## Trading the signal on the holdout",
        "",
        "Long when the model predicts 'up', flat otherwise; event-driven engine, next-open fills.",
        "",
        "| Stock | Costs | Strategy return | Sharpe | Max drawdown | Trades | Buy & hold return | Buy & hold Sharpe |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for sym in SYMBOLS:
        sig = hold[hold["symbol"] == sym]["pred_default"].astype(bool)
        bars = data[sym].loc[sig.index[0]:]
        for label, (c, s) in COSTS.items():
            ml = Backtest(bars, MLSignalStrategy(sig), commission=c, slippage=s).run().metrics
            bh = Backtest(bars, BuyAndHold(), commission=c, slippage=s).run().metrics
            lines.append(
                f"| {sym} | {label} | {ml['total_return'] * 100:+.1f}% | {ml['sharpe']:.2f} | "
                f"{ml['max_drawdown'] * 100:.1f}% | {ml['num_trades']} | {bh['total_return'] * 100:+.1f}% | "
                f"{bh['sharpe']:.2f} |"
            )
    lines.append("")

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
